"""The whole corpus pipeline: source PDFs → structured chunks (JSON) → embeddings → Chroma.

    python pdf_to_chromadb.py build  [--frameworks ID,ID] [--reset | --resume | --replace]
    python pdf_to_chromadb.py chunk  [--frameworks ID,ID]     PDFs → JSON only, no API calls
    python pdf_to_chromadb.py ocr    [--frameworks ID,ID]     OCR scanned pages into the cache only
    python pdf_to_chromadb.py embed  [--frameworks ID,ID] [--reset | --resume | --replace]
    python pdf_to_chromadb.py stats
    python pdf_to_chromadb.py query "..." [--framework ID] [--sector S] [--k 5]
    python pdf_to_chromadb.py push-index <repo_id> [--public]

Inputs are the PDFs in source_pdfs/<FRAMEWORK_ID>/ and the hand-written
data/frameworks/<sector>/<FRAMEWORK_ID>/metadata.json beside each framework's
output (official name, regulator, dates, source URL — none of which can be read
reliably off a PDF). Everything else under data/ is generated by `chunk`.

Chunking is structure-aware, because a regulation is already chunked by its
author: one section, article or clause is one obligation, and it is cited by
that number. Splitting anywhere else either cuts a rule in half or glues two
unrelated ones together, and the reader loses the "Section 8(5)" they need to
check the answer against the source. So, per document:

1. **Extract** text line by line with PyMuPDF, dropping what is print rather
   than law: running headers and footers (lines repeating across pages),
   footnote markers and footnote bodies (set in a smaller font than the body),
   page numbers and tables of contents. Tables are read row by row, so a
   penalty schedule keeps each breach next to its penalty instead of arriving
   column by column. Scanned pages, which have no text layer, are read with
   Tesseract OCR (see ocr_pages) and cached beside the PDF.
2. **Detect the heading style** the document actually uses — Indian gazette
   sections ("12. Title.—"), articles ("Article 33"), or decimal clauses
   ("7.5.2 Creating and updating") — by trying each and keeping the one that
   finds the most plausible headings. Chapters, parts and schedules are
   recognised in every style. Section numbers must run in sequence, which is
   what keeps a numbered list inside a section from passing for new sections.
3. **Split each section** into chunks of at most 512 tokens (header included),
   on paragraph → line → sentence → clause boundaries with a 64-token overlap.
   A section that fits is one chunk; most do.
4. **Prefix a locating header** to every chunk — `[framework | regulator |
   date]` and the breadcrumb `framework > Chapter > Section` — and embed that.
   A clause is only findable by what it *is about* if the embedding knows where
   it sits; "the penalty shall not exceed ₹250 crore" means nothing without
   "DPDP Act > Schedule".

The JSON schema matches what the app, the eval and Chroma metadata expect:
`embed_text` is what gets embedded, `text` is what a reader is shown.
"""

