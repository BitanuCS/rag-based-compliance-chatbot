def to_record(chunk_):
    """A chunk as (page_content, metadata) for Chroma.

    Chroma stores str/int/float/bool only, so None is dropped and lists joined.
    header_chars lets the app slice the embedding header back off for display.
    """
    from langchain_core.documents import Document

    meta = {}
    for key in CARRY:
        value = chunk_.get(key)
        if value is None:
            continue
        meta[key] = "/".join(map(str, value)) if isinstance(value, list) else value
    meta["header_chars"] = len(chunk_["embed_text"]) - len(chunk_["text"])
    meta["parent_chunk_id"] = chunk_["section_id"]
    meta["split_index"] = chunk_["part_index"]
    meta["split_total"] = chunk_["part_total"]
    return Document(page_content=chunk_["embed_text"], metadata=meta)


def embed(frameworks=None, reset=False, assume_yes=False, replace=False, resume=False):
    """data/all_chunks.json → embeddings → Chroma."""
    if not ALL_CHUNKS.exists():
        sys.exit(f"no {ALL_CHUNKS} — run `python pdf_to_chromadb.py chunk` first")
    chunks = json.loads(ALL_CHUNKS.read_text())
    if frameworks:
        chunks = [c for c in chunks if c["framework_id"] in set(frameworks)]

    if reset:
        # The one place a collection built with another embedding model may be
        # opened — to delete it.
        store = get_store(check_model=False)
        existing = store._collection.count()
        if existing and not assume_yes:
            answer = input(f"delete collection {COLLECTION!r} ({existing} records)? [y/N] ")
            if answer.strip().lower() not in {"y", "yes"}:
                sys.exit("aborted")
        store.delete_collection()
        get_store.cache_clear()
        indexed_frameworks.cache_clear()
        print(f"reset collection {COLLECTION!r}")

    store = get_store()
    if replace:
        if not frameworks:
            sys.exit("--replace needs --frameworks; use --reset to drop everything")
        # Clearing the framework first is what makes a targeted re-embed
        # equivalent to a rebuild of that slice: a section that used to split
        # into three parts and now splits into two would otherwise leave its
        # old third part behind.
        before = store._collection.count()
        store._collection.delete(where={"framework_id": {"$in": list(frameworks)}})
        print(f"replace: removed {before - store._collection.count()} records")

    ids = [c["chunk_id"] for c in chunks]
    if resume:
        # The free embedding tier has a daily quota a full build can run into.
        # Ids are deterministic, so whatever an interrupted run wrote is exactly
        # the set to skip.
        done = set(store.get(ids=ids, include=[])["ids"])
        chunks = [c for c in chunks if c["chunk_id"] not in done]
        print(f"resume: {len(done)} records already indexed, {len(chunks)} to go")

    documents = [to_record(c) for c in chunks]
    ids = [c["chunk_id"] for c in chunks]
    print(f"embedding {len(documents)} chunks with {EMBED_ID}...")
    for start in range(0, len(documents), BATCH_SIZE):
        window = slice(start, start + BATCH_SIZE)
        store.add_documents(documents[window], ids=ids[window])
        print(f"  {min(start + BATCH_SIZE, len(documents))}/{len(documents)}", flush=True)
    print(f"\nstored {len(documents)} records in {CHROMA_DIR}")


