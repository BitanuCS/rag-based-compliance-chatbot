def framework_dirs(frameworks=None):
    """{framework_id: data/frameworks/<sector>/<id>/} for every framework with metadata."""
    found = {path.parent.name: path.parent for path in sorted(FRAMEWORKS_DIR.glob("*/*/metadata.json"))}
    if frameworks:
        unknown = set(frameworks) - set(found)
        if unknown:
            sys.exit(f"unknown framework ids: {', '.join(sorted(unknown))}")
        found = {fid: path for fid, path in found.items() if fid in frameworks}
    return found


def load_meta(folder):
    meta = json.loads((folder / "metadata.json").read_text())
    meta["sector"] = folder.parent.name
    return meta


def chunk(frameworks=None):
    """PDFs → data/ JSON. Rewrites the selected frameworks, keeps the rest."""
    targets = framework_dirs(frameworks)
    existing = json.loads(ALL_CHUNKS.read_text()) if ALL_CHUNKS.exists() and frameworks else []
    kept = [c for c in existing if c["framework_id"] not in targets]
    report = json.loads((CORPUS_DIR / "qa_report.json").read_text()) if frameworks and (CORPUS_DIR / "qa_report.json").exists() else {}

    all_new = []
    for framework_id, folder in targets.items():
        meta = load_meta(folder)
        pdfs = sorted((PDF_DIR / framework_id).glob("*.pdf"))
        if not pdfs:
            sys.exit(f"no PDFs in {PDF_DIR / framework_id}")
        for stale in [*folder.glob("*.chunks.json"), *folder.glob("*.document.json")]:
            stale.unlink()

        # The framework's own PDF first; any others are supplementary documents
        # and get their stem in the id, as in the original corpus.
        pdfs.sort(key=lambda p: p.stem != framework_id)
        for pdf in pdfs:
            doc_id = framework_id if pdf.stem == framework_id else f"{framework_id}__{pdf.stem}"
            document, chunks = chunk_document(pdf, meta, doc_id)
            (folder / f"{doc_id}.document.json").write_text(json.dumps(document, indent=2, ensure_ascii=False))
            (folder / f"{doc_id}.chunks.json").write_text(json.dumps(chunks, indent=2, ensure_ascii=False))
            all_new.extend(chunks)

            tokens = [c["token_estimate"] for c in chunks]
            report[doc_id] = {
                "strategy": document["structure_strategy"],
                "scores": document["structure_scores"],
                "sections": len(document["sections"]),
                "chunks": len(chunks),
                "split_sections": sum(1 for c in chunks if c["part_index"] == 2),
                "median_tokens": int(statistics.median(tokens)) if tokens else 0,
                **document["extraction"],
            }
            ext = document["extraction"]
            print(
                f"  {doc_id:<58} {document['structure_strategy']:<8} "
                f"{len(document['sections']):>4} sections → {len(chunks):>4} chunks  "
                f"pages {ext.get('text_pages', 0)}/{ext['pages']}  tables {ext.get('tables', 0)}"
                + (f"  ocr {ext['ocr_pages']}" if ext.get("ocr_pages") else "")
            )

    chunks = kept + all_new
    ALL_CHUNKS.write_text(json.dumps(chunks, indent=2, ensure_ascii=False))
    (CORPUS_DIR / "qa_report.json").write_text(json.dumps(report, indent=2))
    _write_index(chunks)
    checks = _validate(chunks)
    print(f"\n{len(chunks)} chunks from {len({c['framework_id'] for c in chunks})} frameworks → {ALL_CHUNKS}")
    for check in checks["checks"]:
        print(f"  {check['status']:<4} {check['check']}" + (f"  e.g. {check['examples'][:3]}" if check["examples"] else ""))
    return chunks


def _write_index(chunks):
    documents = Counter(c["source_pdf"] for c in chunks)
    by_framework = Counter(c["framework_id"] for c in chunks)
    index = {
        "generated_by": PARSER,
        "frameworks": len(by_framework),
        "documents": len(documents),
        "total_sections": len({c["section_id"] for c in chunks}),
        "total_chunks": len(chunks),
        "chunks_per_framework": dict(sorted(by_framework.items())),
    }
    (CORPUS_DIR / "index.json").write_text(json.dumps(index, indent=2))


def _validate(chunks):
    """The invariants everything downstream relies on, recorded and printed."""
    def check(name, failures, checked):
        return {"check": name, "status": "FAIL" if failures else "PASS",
                "failed": len(failures), "checked": checked, "examples": failures[:5]}

    ids = Counter(c["chunk_id"] for c in chunks)
    checks = [
        check("chunk_id uniqueness", [i for i, n in ids.items() if n > 1], len(chunks)),
        check(f"every chunk within {EMBED_LIMIT} tokens",
              [c["chunk_id"] for c in chunks if c["token_estimate"] > EMBED_LIMIT], len(chunks)),
        check("embed_text = header + text",
              [c["chunk_id"] for c in chunks if not c["embed_text"].endswith(c["text"])], len(chunks)),
        check(f"section titles under {MAX_TITLE_CHARS} chars",
              [c["chunk_id"] for c in chunks if len(c["section_title"] or "") > MAX_TITLE_CHARS], len(chunks)),
        check("no empty chunks", [c["chunk_id"] for c in chunks if not c["text"].strip()], len(chunks)),
    ]
    result = {
        "chunks": len(chunks),
        "frameworks": len({c["framework_id"] for c in chunks}),
        "chunks_per_framework": dict(sorted(Counter(c["framework_id"] for c in chunks).items())),
        "checks": checks,
    }
    (CORPUS_DIR / "validation.json").write_text(json.dumps(result, indent=2))
    return result


