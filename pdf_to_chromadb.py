def _body_font_size(doc):
    """The most common span size, weighted by characters: the document's body text."""
    sizes = Counter()
    for page in doc:
        for block in page.get_text("dict")["blocks"]:
            for line in block.get("lines", []):
                for span in line["spans"]:
                    sizes[round(span["size"], 1)] += len(span["text"].strip())
    return sizes.most_common(1)[0][0] if sizes else 10.0


def _body_column(doc, body_size):
    """(left, right) x-range of the body text, from where body-size lines sit.

    Gazette Acts print each section's title in the page margin, outside this
    column; anything small set outside it is a margin note, not body text.
    """
    lefts, rights = [], []
    for page in doc:
        for block in page.get_text("dict")["blocks"]:
            for line in block.get("lines", []):
                spans = [s for s in line["spans"] if s["text"].strip()]
                if spans and abs(max(s["size"] for s in spans) - body_size) < 0.6:
                    lefts.append(line["bbox"][0])
                    rights.append(line["bbox"][2])
    if not lefts:
        return 0, float("inf")
    lefts.sort()
    rights.sort()
    return lefts[len(lefts) // 20], rights[len(rights) * 19 // 20]


# Margin notes are joined into one title when their lines are this close.
MARGIN_LINE_GAP = 14
# A margin note titles the section whose first line starts within this distance.
MARGIN_TITLE_SNAP = 12


def _attach_margin_titles(items, notes):
    """Fold gazette margin notes into the section lines they sit beside.

    "26. The Chairperson shall…" printed beside the margin note "Powers of
    Chairperson." becomes "26. Powers of Chairperson.—The Chairperson shall…",
    the form the Companies Act prints inline — so the section keeps its title,
    and the note's words stop landing mid-sentence in the body text.
    """
    groups = []
    for y, text in sorted(notes):
        if groups and y - groups[-1][1] <= MARGIN_LINE_GAP:
            groups[-1] = (groups[-1][0], y, f"{groups[-1][2]} {text}")
        else:
            groups.append((y, y, text))

    titled = 0
    for i, (y, x, lines) in enumerate(items):
        match = GAZETTE_RE.match(lines[0]) if len(lines) == 1 else None
        if not match or GAZETTE_TITLE_RE.match(match.group(3)):
            continue
        near = [g for g in groups if abs(g[0] - y) <= MARGIN_TITLE_SNAP]
        if near:
            title = near[0][2].strip().rstrip(".")
            items[i] = (y, x, [f"{match.group(1)}{match.group(2)}. {title}.—{match.group(3)}"])
            titled += 1
    return titled


def _cell_text(page, rect):
    """A table cell's text, read with normal word spacing.

    find_tables() extracts cell text glyph by glyph and drops the spaces in some
    gazette fonts ("Breachinobserving"); clipping the ordinary text extractor to
    the cell's rectangle keeps them.
    """
    if rect is None:
        return ""
    return " ".join(page.get_text("text", clip=rect).split())


def _render_table(page, table):
    """A table as one line per row, each cell labelled by its column header.

    Rows whose first cell is empty continue the row above — a long cell wraps
    onto a new table row in gazette layout — so they are merged back in. The
    result reads "Sl. No.: 1. | Breach…: Breach in observing… | Penalty: May
    extend to two hundred and fifty crore rupees." — one fact per line, header
    attached, which is what a search for the penalty has to find.
    """
    rows = [[_cell_text(page, cell) for cell in row.cells] for row in table.rows]
    rows = [row for row in rows if any(row)]
    if len(rows) < 2:
        return []
    header, body = rows[0], rows[1:]
    # Column-number rows "(1) (2) (3)" carry nothing.
    body = [row for row in body if not all(re.fullmatch(r"\(?\d+\)?", c or "") for c in row)]

    merged = []
    for row in body:
        if merged and not row[0] and len(row) == len(merged[-1]):
            merged[-1] = [f"{a} {b}".strip() for a, b in zip(merged[-1], row)]
        else:
            merged.append(row)

    lines = []
    for row in merged:
        cells = []
        for name, value in zip(header, row):
            if not value:
                continue
            cells.append(f"{name}: {value}" if name else value)
        if cells:
            lines.append(" | ".join(cells))
    return lines


# --- OCR for scanned pages ----------------------------------------------------

# Six of the source PDFs (every SEBI document, the Consumer Protection Rules) are
# scans: images with no text layer. Tesseract reads them, locally — no quota, no
# network, and the same input always gives the same text, which a rebuild that
# has to be reproducible depends on. PyMuPDF drives it and hands back text
# blocks with their positions, so a scanned page goes through the same running
# header/footer filter as a born-digital one.
OCR_DPI = int(os.getenv("OCR_DPI", "300"))
OCR_LANGUAGE = os.getenv("OCR_LANGUAGE", "eng")
OCR_WORKERS = int(os.getenv("OCR_WORKERS", str(max(1, (os.cpu_count() or 2) - 1))))
# Below this many characters a page is treated as having no text layer.
MIN_TEXT_CHARS = 30


def _ocr_cache(pdf_path):
    return pdf_path.with_suffix(".ocr.json")


def _ocr_one(args):
    """[(y_fraction, block_text)] for one page. Runs in a worker process."""
    import pymupdf

    path, page_number = args
    page = pymupdf.open(path)[page_number - 1]
    textpage = page.get_textpage_ocr(language=OCR_LANGUAGE, dpi=OCR_DPI, full=True)
    height = page.rect.height or 1
    blocks = page.get_text("blocks", textpage=textpage, sort=True)
    return page_number, [(b[1] / height, b[4]) for b in blocks if b[4].strip()]


def ocr_pages(pdf_path, pages):
    """{page_number: [(y_fraction, block_text)]} for scanned pages.

    Cached beside the PDF, so tuning the chunker never re-runs OCR. Pages are
    spread across processes: Tesseract is single-threaded and CPU-bound, so a
    206-page scan takes minutes on all cores instead of a quarter of an hour.
    """
    from concurrent.futures import ProcessPoolExecutor

    cache_file = _ocr_cache(pdf_path)
    cache = json.loads(cache_file.read_text()) if cache_file.exists() else {}
    todo = [p for p in pages if str(p) not in cache]
    if todo:
        print(f"    OCR {pdf_path.name}: {len(todo)} pages on {OCR_WORKERS} workers (tesseract)", flush=True)
        with ProcessPoolExecutor(max_workers=OCR_WORKERS) as pool:
            for done, (page, blocks) in enumerate(pool.map(_ocr_one, [(str(pdf_path), p) for p in todo]), start=1):
                cache[str(page)] = blocks
                if done % 20 == 0 or done == len(todo):
                    cache_file.write_text(json.dumps(cache, ensure_ascii=False))
                    print(f"      {done}/{len(todo)} pages", flush=True)
    return {p: cache.get(str(p), []) for p in pages}


def ocr(frameworks=None):
    """OCR every scanned page into the cache, without touching the corpus JSON."""
    import pymupdf

    for framework_id in framework_dirs(frameworks):
        for pdf in sorted((PDF_DIR / framework_id).glob("*.pdf")):
            doc = pymupdf.open(pdf)
            scanned = [n for n, page in enumerate(doc, start=1) if len(page.get_text().strip()) < MIN_TEXT_CHARS]
            if scanned:
                ocr_pages(pdf, scanned)


COLUMN_NUMBER_RE = re.compile(r"^\((\d{1,2})\)$")
SERIAL_RE = re.compile(r"^\d{1,3}\.?$")
# Lines that close a gazette page after its last table: the signing officer and
# the press imprint, not table content.
TABLE_END_RE = re.compile(r"^(UPLOADED|MGIPMRND|PRINTED|PUBLISHED|DR\.|SHRI|MS\.|MR\.|—{3,}|_{3,})")
# Narrowest strip of empty space that counts as the gutter between two columns.
GUTTER_MIN = 6
# How far above the (1)(2)(3) row the column headers sit.
HEADER_REACH = 32


def _column_number_table(page):
    """Rebuild a gazette table that has no ruling lines. Returns (bbox, lines) or None.

    Indian gazette schedules print a column-number row — "(1) (2) (3)" — under
    their headers, and draw no grid, so line-based table detection sees only
    text. Read as text, a three-column penalty schedule interleaves its columns
    line by line ("May extend to two / take reasonable security…") and the
    breach → penalty mapping is gone. The column numbers mark where each
    column sits: every word below them is assigned to the nearest column, and a
    serial number in the first column starts a new row.
    """
    words = page.get_text("words", sort=True)
    numbers = [w for w in words if COLUMN_NUMBER_RE.match(w[4])]
    rows_by_y = {}
    for w in numbers:
        rows_by_y.setdefault(round(w[1] / 3), []).append(w)
    def alone(ws):
        # The marker row holds nothing but column numbers. "(3) Where any
        # change occurs…" beside "(1)" in a sub-section is prose, not a header.
        y = ws[0][1]
        return all(COLUMN_NUMBER_RE.match(w[4]) for w in words if abs(w[1] - y) < 3)

    marker = next(
        (sorted(ws, key=lambda w: w[0]) for ws in rows_by_y.values()
         if len(ws) >= 2
         and [int(COLUMN_NUMBER_RE.match(w[4]).group(1)) for w in sorted(ws, key=lambda w: w[0])]
         == list(range(1, len(ws) + 1))
         and alone(ws)),
        None,
    )
    if not marker:
        return None

    centres = [(w[0] + w[2]) / 2 for w in marker]
    marker_top, marker_bottom = min(w[1] for w in marker), max(w[3] for w in marker)

    # Column boundaries go in the gutters: scanning right from a column's
    # marker, the first strip at least GUTTER_MIN wide that no body word
    # crosses. The markers are centred over columns of very different widths,
    # so the midpoint between them would cut into the wide one — and the widest
    # gap is not safe either, since a short column leaves open space on its
    # right that is wider than the gutter on its left.
    body = []
    for w in words:
        if w[1] <= marker_bottom:
            continue
        if TABLE_END_RE.match(w[4]):
            break  # the signature and imprint run full width, across the gutters
        body.append(w)
    left_edge = int(min((w[0] for w in body), default=0))
    covered = set()
    for w in body:
        covered.update(range(int(w[0]), int(w[2]) + 1))
    bounds = []
    for a, b in zip(centres, centres[1:]):
        best, run = None, []
        for x in range(max(int(a), left_edge), int(b) + 1):
            if x not in covered:
                run.append(x)
                continue
            if len(run) >= GUTTER_MIN:
                best = run
                break
            run = []
        if best is None and len(run) >= GUTTER_MIN:
            best = run
        bounds.append((best[0] + best[-1]) / 2 if best else (a + b) / 2)

    def column(word):
        x = (word[0] + word[2]) / 2
        return sum(x > b for b in bounds)

    header = [[] for _ in marker]
    for w in words:
        if marker_top - HEADER_REACH <= w[1] < marker_top - 1:
            header[column(w)].append(w[4])

    rows, bottom = [], marker_bottom
    for w in words:
        if w[1] <= marker_bottom:
            continue
        if TABLE_END_RE.match(w[4]):
            break
        col = column(w)
        if col == 0 and SERIAL_RE.match(w[4]):
            rows.append([[] for _ in marker])
        if rows:
            rows[-1][col].append(w[4])
            bottom = max(bottom, w[3])
    if len(rows) < 2:
        return None

    names = [" ".join(h) for h in header]
    lines = []
    for row in rows:
        cells = [" ".join(c) for c in row]
        lines.append(" | ".join(f"{n}: {c}" if n else c for n, c in zip(names, cells) if c))
    import pymupdf

    bbox = pymupdf.Rect(page.rect.x0, marker_top - HEADER_REACH, page.rect.x1, bottom + 1)
    return bbox, lines


def extract_lines(pdf_path):
    """[(page_number, text)] for every line of body text, plus extraction stats."""
    import pymupdf

    doc = pymupdf.open(pdf_path)
    body_size = _body_font_size(doc)
    small = body_size * SMALL_FONT_RATIO
    left, right = _body_column(doc, body_size)
    stats = Counter(pages=len(doc))

    scanned = [n for n, page in enumerate(doc, start=1) if len(page.get_text().strip()) < MIN_TEXT_CHARS]
    # OCR=off chunks a document's text layer alone, for a fast pass that leaves
    # scanned pages out (they are counted, so the gap is visible in qa_report).
    if scanned and os.getenv("OCR", "on").lower() == "off":
        stats["scanned_pages_skipped"] = len(scanned)
        scanned = []
    ocr = ocr_pages(pdf_path, scanned) if scanned else {}

    raw = []  # (page_no, text, y_fraction)
    for page_no, page in enumerate(doc, start=1):
        if page_no in ocr:
            # OCR has no font sizes, so no footnote or margin-note handling —
            # but block positions still let running headers and footers go.
            lines = [(y, _clean(line)) for y, block in ocr[page_no] for line in block.splitlines()]
            lines = [(y, line) for y, line in lines if line]
            if lines:
                stats["text_pages"] += 1
                stats["ocr_pages"] += 1
            raw.extend((page_no, line, y) for y, line in lines)
            continue

        height = page.rect.height or 1
        try:
            tables = [t for t in page.find_tables(use_layout=False).tables if t.row_count >= 2 and t.col_count >= 2]
        except Exception:
            tables = []
        # A "table" with a column in the margin is the gazette layout itself —
        # margin notes beside body text — not a table.
        tables = [
            t for t in tables
            if not any(
                cell and (cell[2] <= left + 2 or cell[0] >= right - 2)
                for cell in t.rows[0].cells
            )
        ]
        boxes = [pymupdf.Rect(t.bbox) for t in tables]
        rebuilt = None if tables else _column_number_table(page)
        if rebuilt:
            boxes.append(rebuilt[0])

        items = []  # (y, x, [lines]) so tables slot in at their position on the page
        notes = []  # (y, text) margin notes on this page
        in_footnotes = False
        for block in page.get_text("dict", sort=True)["blocks"]:
            for line in block.get("lines", []):
                rect = pymupdf.Rect(line["bbox"])
                centre = pymupdf.Point((rect.x0 + rect.x1) / 2, (rect.y0 + rect.y1) / 2)
                if any(centre in box for box in boxes):
                    continue
                spans = [span for span in line["spans"] if span["text"].strip()]
                if not spans:
                    continue
                size = max(span["size"] for span in spans)
                smaller = size <= body_size * FOOTNOTE_FONT_RATIO
                if smaller and (rect.x1 <= left + 2 or rect.x0 >= right - 2):
                    notes.append((rect.y0, _clean("".join(span["text"] for span in spans))))
                    continue
                if (
                    not in_footnotes
                    and smaller
                    and rect.y0 / height > FOOTNOTE_ZONE
                    and FOOTNOTE_START_RE.match("".join(span["text"] for span in spans))
                ):
                    in_footnotes = True
                if in_footnotes and smaller:
                    stats["footnote_lines_removed"] += 1
                    continue
                kept = []
                for span in line["spans"]:
                    text = span["text"].strip()
                    # Small capitals ("P" + "ENALTIES AND ADJUDICATION" in a
                    # smaller size) are a heading, not a footnote: footnote
                    # markers are digits, footnote bodies are mixed case.
                    small_caps = len(text) > 1 and text.replace(" ", "").isalpha() and text.isupper()
                    if span["size"] < small and text and not small_caps:
                        stats["small_font_chars_removed"] += len(text)
                        continue
                    kept.append(span["text"])
                text = _clean("".join(kept))
                if text:
                    items.append((rect.y0, rect.x0, [text]))
        for table, box in zip(tables, boxes):
            rendered = _render_table(page, table)
            if rendered:
                stats["tables"] += 1
                items.append((box.y0, box.x0, rendered))
        if rebuilt:
            stats["tables_rebuilt_from_column_numbers"] += 1
            items.append((rebuilt[0].y0, rebuilt[0].x0, rebuilt[1]))

        items.sort(key=lambda item: (round(item[0]), item[1]))
        if notes:
            stats["margin_note_lines"] += len(notes)
            stats["margin_titles_attached"] += _attach_margin_titles(items, notes)
        if items:
            stats["text_pages"] += 1
        for y, _, lines in items:
            for text in lines:
                raw.append((page_no, text, y / height))

    lines = _drop_print_furniture(raw, len(doc), stats)
    lines = _drop_toc(lines, stats)
    stats["chars_extracted"] = sum(len(text) for _, text in lines)
    stats["body_font_size"] = body_size
    return lines, dict(stats)


def _clean(text):
    text = text.replace("​", "").replace("\xa0", " ").replace("\t", " ")
    return " ".join(text.split())


DOT_LEADER_RE = re.compile(r"\.{4,}\s*\d+\s*$|(?:\s\.){4,}")
PAGE_NUMBER_RE = re.compile(r"^(?:page\s*)?[-–]?\s*\d{1,4}\s*[-–]?(?:\s*of\s*\d+)?$", re.IGNORECASE)


def _drop_print_furniture(raw, page_count, stats):
    """Remove running headers/footers, page numbers and TOC dot leaders."""
    def shape(text):
        return re.sub(r"\d+", "#", text.lower())

    edge = Counter()
    for page_no, text, y in raw:
        if y < EDGE_BAND or y > 1 - EDGE_BAND:
            edge[(shape(text))] += 1
    threshold = max(3, RUNNING_LINE_SHARE * page_count)
    running = {key for key, count in edge.items() if count >= threshold}
    stats["distinct_running_patterns"] = len(running)

    kept = []
    for page_no, text, y in raw:
        at_edge = y < EDGE_BAND or y > 1 - EDGE_BAND
        if at_edge and (shape(text) in running or PAGE_NUMBER_RE.match(text)):
            stats["running_lines_removed"] += 1
            continue
        if DOT_LEADER_RE.search(text):
            stats["toc_lines_removed"] += 1
            continue
        kept.append((page_no, text))
    return kept


def _structural_number(text):
    """The heading number a line would carry if it were a heading, else None."""
    for pattern in (GAZETTE_RE, ARTICLE_RE, DECIMAL_RE, DECIMAL_NUMBER_ONLY_RE):
        match = pattern.match(text)
        if match and len(text) <= 150:
            return "".join(g for g in match.groups()[:2] if g and pattern is GAZETTE_RE) or match.group(1)
    if CHAPTER_RE.match(text) or SCHEDULE_RE.match(text):
        return ""
    return None


# A table of contents is a dense run of heading-shaped lines — at least this many,
# no more than TOC_MAX_GAP lines apart — near the front of the document, whose
# numbers then reappear as the real headings.
TOC_MIN_RUN = 12
TOC_MAX_GAP = 2
TOC_FRONT_SHARE = 0.25
TOC_REPEAT_SHARE = 0.5


def _drop_toc(lines, stats):
    """Remove tables of contents that have no dot leaders to give them away.

    The Companies Act opens with its "Arrangement of Sections": every section
    number and title, one per line, ending with the Schedules. Read as body text
    it is 470 empty sections, and its closing schedule list makes everything
    after it look like a schedule. Real sections have body text between their
    headings; a contents list does not — so a long run of headings with almost
    nothing between them, at the front, whose numbers come back later, is the
    contents.
    """
    marks = [(i, number) for i, (_, text) in enumerate(lines) if (number := _structural_number(text)) is not None]
    front = len(lines) * TOC_FRONT_SHARE
    drop = set()

    run = []
    for mark in [*marks, (None, None)]:
        # A number already in the run means the body has begun: the contents
        # ended on the line before, however close the first real section sits.
        restarted = mark[1] and mark[1] in {n for _, n in run}
        if run and (mark[0] is None or mark[0] - run[-1][0] > TOC_MAX_GAP or restarted):
            numbers = [n for _, n in run if n]
            later = {n for i, n in marks if i > run[-1][0] and n}
            if (
                len(run) >= TOC_MIN_RUN
                and run[0][0] < front
                and numbers
                and sum(n in later for n in numbers) / len(numbers) >= TOC_REPEAT_SHARE
            ):
                drop.update(range(run[0][0], run[-1][0] + 1))
            run = []
        if mark[0] is not None:
            run.append(mark)

    stats["toc_lines_removed"] = stats.get("toc_lines_removed", 0) + len(drop)
    return [line for i, line in enumerate(lines) if i not in drop]


# --- 2. structure ------------------------------------------------------------

CHAPTER_RE = re.compile(r"^(CHAPTER|Chapter|PART|Part)\s+([IVXLC]+|\d+[A-Z]?)\b\.?\s*[-–—:]?\s*(.*)$")
SCHEDULE_RE = re.compile(
    r"^(?:THE\s+)?(?:(?:FIRST|SECOND|THIRD|FOURTH|FIFTH|SIXTH|SEVENTH|EIGHTH|NINTH|TENTH)\s+)?"
    r"(SCHEDULE|ANNEXURE|ANNEX|APPENDIX)(?:\s*[-–—]?\s*([IVXLC\d]+|[A-Z]))?\b\.?\s*(.*)$"
)

# "149. Company to have Board of Directors.—(1) Every company…" or "4. (1) A person…"
GAZETTE_RE = re.compile(r"^\[?(\d{1,3})([A-Z]{0,3})\.\s*(.*)$")
GAZETTE_TITLE_RE = re.compile(r"^([A-Z][^—–]{2,%d}?)\.?\s*[-–—]{1,2}\s*" % MAX_TITLE_CHARS)
# "Article 33" alone on its line; the title follows on the next.
ARTICLE_RE = re.compile(r"^Article\s+(\d{1,3}[a-z]?)\s*$")
# "7.5.2 Creating and updating", "A.5.1 Policies…", "Requirement 3: Protect…"
DECIMAL_RE = re.compile(r"^((?:[A-Z]\.)?\d{1,2}(?:\.\d{1,2}){0,3})\.?\s+([A-Z][^\n]{2,%d})$" % MAX_TITLE_CHARS)
DECIMAL_NUMBER_ONLY_RE = re.compile(r"^((?:[A-Z]\.)?\d{1,2}(?:\.\d{1,2}){1,3})\.?$")
REQUIREMENT_RE = re.compile(r"^(Requirement\s+\d{1,2})\s*:?\s+(.{3,%d})$" % MAX_TITLE_CHARS)


def _title_case(text):
    """CHAPTER titles are set in capitals; read them as words."""
    return text.title() if text.isupper() else text


class Heading:
    __slots__ = ("index", "kind", "number", "title", "level")

    def __init__(self, index, kind, number, title="", level=1):
        self.index, self.kind, self.number, self.title, self.level = index, kind, number, title, level


def _seq_key(number):
    match = re.match(r"(\d+)([A-Z]*)", number)
    return (int(match.group(1)), match.group(2)) if match else None


def find_headings(lines, strategy):
    """Headings for one strategy, as Heading objects over line indices.

    Chapter/part/schedule headings are found in every strategy. Section headings
    depend on it, and gazette and article numbers must run in sequence (the next
    number, a lettered insertion like 12A, or a short gap for repealed sections).
    That one rule is what separates "12. Duties of…" from item 2 of a numbered
    list inside section 11.
    """
    texts = [text for _, text in lines]
    headings, last, in_schedule = [], None, False

    for i, text in enumerate(texts):
        match = SCHEDULE_RE.match(text)
        if match and text.split()[0].isupper() and len(text) <= MAX_TITLE_CHARS:
            label = " ".join(p for p in (match.group(1).title(), match.group(2)) if p)
            title = match.group(3).strip()
            headings.append(Heading(i, "schedule", label, _title_case(title)))
            in_schedule = True
            continue

        match = CHAPTER_RE.match(text)
        if match and len(text) <= MAX_TITLE_CHARS and not in_schedule:
            title = match.group(3).strip()
            if not title and i + 1 < len(texts) and texts[i + 1].isupper() and len(texts[i + 1]) <= MAX_TITLE_CHARS:
                title = texts[i + 1]
            headings.append(Heading(i, "chapter", f"{match.group(1).title()} {match.group(2)}", _title_case(title)))
            continue

        if in_schedule:
            continue

        if strategy == "gazette":
            match = GAZETTE_RE.match(text)
            if not match:
                continue
            key = (int(match.group(1)), match.group(2))
            rest = match.group(3)
            title_match = GAZETTE_TITLE_RE.match(rest)
            title = title_match.group(1).strip() if title_match else ""
            # A printed title ("44. Amendments.—") is strong evidence on its
            # own, so it may open a document anywhere and jump a run of omitted
            # sections. A bare number must follow closely: that is all that
            # separates "4. (1) A person…" from item 4 of a list.
            reach = 10 if title else 3
            plausible = last is None and (key[0] <= 3 or bool(title))
            if last is not None:
                plausible = (
                    (key[0] == last[0] and key[1] > last[1])
                    or (key[0] > last[0] and key[0] - last[0] <= reach and not key[1])
                    or (key[0] > last[0] and key[0] - last[0] <= 1 and key[1])
                )
            if not plausible:
                continue
            headings.append(Heading(i, "section", f"{key[0]}{key[1]}", title))
            last = key

        elif strategy == "article":
            match = ARTICLE_RE.match(text)
            if not match:
                continue
            key = _seq_key(match.group(1))
            if last is not None and not (key > last and key[0] - last[0] <= 3):
                continue
            title = texts[i + 1] if i + 1 < len(texts) and len(texts[i + 1]) <= MAX_TITLE_CHARS else ""
            headings.append(Heading(i, "section", f"Article {match.group(1)}", title))
            last = key

        elif strategy == "decimal":
            match = REQUIREMENT_RE.match(text)
            if match:
                headings.append(Heading(i, "section", match.group(1), match.group(2).strip(), level=1))
                continue
            match = DECIMAL_RE.match(text)
            number = title = None
            if match and not text.rstrip().endswith((".", ";", ",", ":")):
                number, title = match.group(1), match.group(2).strip()
            else:
                match = DECIMAL_NUMBER_ONLY_RE.match(text)
                nxt = texts[i + 1] if i + 1 < len(texts) else ""
                if match and nxt[:1].isupper() and len(nxt) <= MAX_TITLE_CHARS and not nxt.endswith("."):
                    number, title = match.group(1), nxt
            if number:
                headings.append(Heading(i, "section", number, title, level=number.count(".") + 1))

    return headings


STRATEGIES = ("gazette", "article", "decimal")


def choose_strategy(lines):
    """The heading style this document uses: whichever finds the most sections."""
    scores = {s: sum(h.kind == "section" for h in find_headings(lines, s)) for s in STRATEGIES}
    best = max(scores, key=scores.get)
    return (best if scores[best] >= 3 else "none"), scores


def reflow(lines):
    """Join PDF lines back into paragraphs.

    A line break is kept where the previous line ends a sentence or clause, or
    where the next starts a list item; everywhere else it is the PDF's line
    wrap, and becomes a space. Words hyphenated across a wrap are rejoined.
    """
    out = ""
    for text in lines:
        if not out:
            out = text
            continue
        starts_item = re.match(r"^(\(?[a-z0-9ivxA-Z]{1,4}\)|[a-z]\.|\d+(\.\d+)*\.?\s|[•▪●\-–] |Provided|Explanation|Illustration)", text)
        if out.endswith("-") and text[:1].islower() and not out.endswith(" -"):
            out = out[:-1] + text
        elif out.endswith((".", ":", ";", "—")) or starts_item or " | " in text:
            out += "\n" + text
        else:
            out += " " + text
    return out


def build_sections(lines, strategy):
    """Lines → sections, each with its heading path and page span."""
    headings = find_headings(lines, strategy) if strategy != "none" else []
    starts = {h.index: h for h in headings}

    sections, chapter, stack = [], None, []
    current = {"number": "0", "title": "Preamble", "chapter": None, "path": [], "lines": []}

    def close():
        if current["lines"]:
            sections.append(dict(current))

    for i, (page, text) in enumerate(lines):
        heading = starts.get(i)
        if heading and heading.kind == "chapter":
            close()
            chapter = f"{heading.number} {heading.title}".strip()
            stack = []
            current = {"number": heading.number, "title": heading.title, "chapter": chapter,
                       "path": [heading.number], "lines": []}
        elif heading and heading.kind == "schedule":
            close()
            chapter, stack = None, []
            current = {"number": heading.number, "title": heading.title, "chapter": None,
                       "path": [heading.number], "lines": []}
        elif heading:
            close()
            if heading.level > 1:
                stack = [h for h in stack if h.level < heading.level]
            else:
                stack = []
            parents = [f"{h.number} {h.title}".strip() for h in stack]
            stack.append(heading)
            current = {"number": heading.number, "title": heading.title, "chapter": chapter,
                       "path": [p for p in (chapter, *parents) if p] + [heading.number],
                       "parents": parents, "lines": []}
        current["lines"].append((page, text))
    close()

    # Strategy "none": no structure found, so pages become sections — still
    # citable, if only by page.
    if strategy == "none":
        by_page = {}
        for page, text in lines:
            by_page.setdefault(page, []).append((page, text))
        sections = [{"number": f"p{p}", "title": f"Page {p}", "chapter": None, "path": [f"p{p}"],
                     "lines": ls} for p, ls in by_page.items()]
    return sections


# --- 3. chunking -------------------------------------------------------------


def breadcrumb(framework_name, section):
    parts = [framework_name]
    if section.get("chapter"):
        parts.append(section["chapter"])
    parts.extend(section.get("parents", []))
    label = f"{section['number']} {section['title']}".strip()
    if label != section.get("chapter"):
        parts.append(label)
    return " > ".join(p[:MAX_TITLE_CHARS] for p in parts)


def _splitter(budget):
    from langchain_text_splitters import RecursiveCharacterTextSplitter

    return RecursiveCharacterTextSplitter.from_tiktoken_encoder(
        encoding_name="cl100k_base",
        chunk_size=budget,
        chunk_overlap=OVERLAP,
        # Legal prose degrades gracefully: paragraph, line, sentence, clause.
        separators=["\n\n", "\n", ". ", "; ", ", ", " ", ""],
    )


def chunk_document(pdf_path, meta, doc_id):
    """One PDF → (document record, chunk records)."""
    lines, stats = extract_lines(pdf_path)
    strategy, scores = choose_strategy(lines)
    sections = build_sections(lines, strategy)

    header_line = f"[{meta['framework_name']} | {meta['regulator']} | {meta['effective_date']}]"
    doc_sections, chunks, dropped = [], [], 0
    for section in sections:
        body = reflow([text for _, text in section["lines"]])
        first_line = section["lines"][0][1]
        if len(body) - len(first_line) < MIN_BODY_CHARS:
            dropped += 1
            continue

        number = len(doc_sections) + 1
        section_id = f"{doc_id}-{number:04d}"
        crumb = breadcrumb(meta["framework_name"], section)
        header = f"{header_line}\n{crumb}\n\n"
        pages = [page for page, _ in section["lines"]]
        doc_sections.append({
            "section_id": section_id,
            "number": section["number"],
            "title": section["title"],
            "chapter": section["chapter"],
            "path": section["path"],
            "page_start": pages[0],
            "page_end": pages[-1],
            "char_count": len(body),
            "text": body,
        })

        budget = EMBED_LIMIT - token_length(header)
        parts = [body] if token_length(body) <= budget else _splitter(budget).split_text(body)
        line_pages = _line_page_offsets(section["lines"], body)
        cursor = 0
        for part_index, part in enumerate(parts, start=1):
            at = body.find(part[:80], max(0, cursor - 2000))
            at = at if at >= 0 else cursor
            cursor = at + len(part)
            chunks.append({
                "chunk_id": f"{section_id}-c{part_index:02d}",
                "framework_id": meta["framework_id"],
                "framework_name": meta["framework_name"],
                "regulator": meta["regulator"],
                "sector": meta["sector"],
                "effective_date": meta["effective_date"],
                "document_status": meta.get("document_status", ""),
                "source_url": meta["source_url"],
                "source_pdf": pdf_path.name,
                "section_id": section_id,
                "section_number": section["number"],
                "section_title": section["title"],
                "section_path": section["path"],
                "chapter": section["chapter"],
                "breadcrumb": crumb,
                "page_start": _page_at(line_pages, at),
                "page_end": _page_at(line_pages, max(at, cursor - 1)),
                "part_index": part_index,
                "part_total": len(parts),
                "text": part,
                "embed_text": header + part,
                "char_count": len(part),
                "token_estimate": token_length(header + part),
            })

    stats.update({"sections_dropped_heading_only": dropped})
    document = {
        "framework_id": meta["framework_id"],
        "framework_name": meta["framework_name"],
        "regulator": meta["regulator"],
        "sector": meta["sector"],
        "effective_date": meta["effective_date"],
        "document_status": meta.get("document_status", ""),
        "source_url": meta["source_url"],
        "source_pdf": pdf_path.name,
        "sha256": hashlib.sha256(pdf_path.read_bytes()).hexdigest(),
        "parsed_at": datetime.now(timezone.utc).isoformat(),
        "parser": PARSER,
        "structure_strategy": strategy,
        "structure_scores": scores,
        "extraction": stats,
        "sections": doc_sections,
    }
    return document, chunks


def _line_page_offsets(section_lines, body):
    """[(char offset in body, page)] marking where each page's text begins."""
    offsets, search_from, last_page = [], 0, None
    for page, text in section_lines:
        if page != last_page:
            at = body.find(text[:40], search_from)
            if at >= 0:
                offsets.append((at, page))
                search_from = at
            last_page = page
    return offsets or [(0, section_lines[0][0])]


def _page_at(offsets, position):
    page = offsets[0][1]
    for at, p in offsets:
        if at > position:
            break
        page = p
    return page


