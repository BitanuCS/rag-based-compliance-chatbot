def stats():
    """What is indexed, and whether it matches the generated corpus."""
    store = get_store()
    metas = store.get(include=["metadatas"])["metadatas"]
    print(f"{CHROMA_DIR}  collection={COLLECTION!r}  model={EMBED_ID}")
    print(f"\n{len(metas)} records from {len({m['parent_chunk_id'] for m in metas})} sections")
    expected = Counter(c["framework_id"] for c in json.loads(ALL_CHUNKS.read_text()))
    got = Counter(m["framework_id"] for m in metas)
    print(f"\n{'framework':<42} {'indexed':>8} {'chunks':>7}")
    missing = []
    for framework, want in sorted(expected.items(), key=lambda kv: -kv[1]):
        flag = "" if got.get(framework, 0) == want else "  ✗"
        if flag:
            missing.append(framework)
        print(f"{framework:<42} {got.get(framework, 0):>8} {want:>7}{flag}")
    print("\nall frameworks fully indexed  ✓" if not missing else f"\nnot fully indexed: {', '.join(missing)}  ✗")


def query(text, k=5, framework=None, sector=None):
    from vectorstore import build_filter

    hits = get_store().similarity_search_with_score(text, k=k, filter=build_filter(framework, sector))
    print(f"query: {text!r}  ({framework or sector or 'all frameworks'}, k={k})\n")
    for rank, (doc, distance) in enumerate(hits, start=1):
        meta = doc.metadata
        pages = f"p{meta['page_start']}" + (f"-{meta['page_end']}" if meta["page_end"] != meta["page_start"] else "")
        part = f" [part {meta['split_index']}/{meta['split_total']}]" if meta["split_total"] > 1 else ""
        print(f"{rank}. {meta['framework_id']}  {pages}  cosine={distance:.4f}{part}")
        print(f"   {meta['breadcrumb']}")
        print(f"   {' '.join(display_text(doc).split())[:220]}...\n")


def push_index(repo_id, private=True):
    """Upload the built index to a Hugging Face dataset repo for the deployed app.

    A container starts with an empty disk and cannot rebuild the index, so the
    built artefact is published here and fetched by vectorstore.ensure_index().
    Run this after any rebuild, or the deployment keeps serving the old index.
    """
    from huggingface_hub import HfApi

    if not _index_present():
        sys.exit(f"no index at {CHROMA_DIR} — run `pdf_to_chromadb.py build` first")
    token = hf_token()
    if not token:
        sys.exit("No HF_TOKEN or HUGGINGFACEHUB_API_TOKEN set; needs *write* permission.")
    api = HfApi(token=token)
    api.create_repo(repo_id, repo_type="dataset", private=private, exist_ok=True)
    print(f"uploading {CHROMA_DIR} to {repo_id} (dataset)…")
    api.upload_folder(repo_id=repo_id, repo_type="dataset", folder_path=str(CHROMA_DIR),
                      commit_message="rebuild compliance index")
    print(f"done. Set CHROMA_INDEX_REPO={repo_id} in the deployment's secrets.")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)

    def scope(cmd):
        cmd.add_argument("--frameworks", help="comma-separated framework ids (default: all)")

    def index_flags(cmd):
        cmd.add_argument("--reset", action="store_true", help="drop the collection first")
        cmd.add_argument("--yes", action="store_true", help="skip the --reset confirmation")
        cmd.add_argument("--replace", action="store_true", help="delete the selected frameworks' records first")
        cmd.add_argument("--resume", action="store_true", help="skip chunks already indexed (continue a stopped build)")

    build_cmd = sub.add_parser("build", help="chunk the PDFs, then embed and store them")
    scope(build_cmd)
    index_flags(build_cmd)
    chunk_cmd = sub.add_parser("chunk", help="PDFs → data/ JSON only (no API calls)")
    scope(chunk_cmd)
    ocr_cmd = sub.add_parser("ocr", help="OCR scanned pages into the cache only")
    scope(ocr_cmd)
    embed_cmd = sub.add_parser("embed", help="data/ JSON → embeddings → Chroma")
    scope(embed_cmd)
    index_flags(embed_cmd)
    sub.add_parser("stats", help="what is indexed, and whether it is complete")
    query_cmd = sub.add_parser("query", help="search the index")
    query_cmd.add_argument("text")
    query_cmd.add_argument("--k", type=int, default=5)
    query_cmd.add_argument("--framework")
    query_cmd.add_argument("--sector")
    push_cmd = sub.add_parser("push-index", help="upload the built index to a HF dataset repo")
    push_cmd.add_argument("repo_id")
    push_cmd.add_argument("--public", action="store_true")

    args = parser.parse_args()
    frameworks = args.frameworks.split(",") if getattr(args, "frameworks", None) else None
    if args.command in {"build", "embed"} and args.resume and (args.reset or args.replace):
        sys.exit("--resume continues an existing index; it cannot be combined with --reset or --replace")

    if args.command in {"build", "chunk"}:
        chunk(frameworks)
    if args.command in {"build", "embed"}:
        embed(frameworks, args.reset, args.yes, args.replace, args.resume)
    elif args.command == "ocr":
        ocr(frameworks)
    elif args.command == "stats":
        stats()
    elif args.command == "query":
        query(args.text, args.k, args.framework, args.sector)
    elif args.command == "push-index":
        push_index(args.repo_id, private=not args.public)


if __name__ == "__main__":
    main()
